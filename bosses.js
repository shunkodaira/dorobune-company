function boss(b) {
  const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return {
    id: b.id, rank: b.rank,
    title: `${b.rankName}戦:${b.tag}`, goal: b.goal, objective: b.objective,
    charName: `${b.surname} ${b.title}`, charSub: `(${b.age}) ${b.dept}`,
    npcLabel: b.title, gaugeLabel: b.gaugeLabel || '機嫌ゲージ',
    tips: b.tips, intro: b.intro, opening: b.opening, winLine: b.winLine, loseZeroLine: b.loseZeroLine,
    timeUpLine: b.timeUpLine, timeUpTitle: b.timeUpTitle, winTitle: b.winTitle, loseTitle: b.loseTitle,
    stampText: b.stampText || '承認',
    exile: b.exile, exileSigner: b.exileSigner || '泥舟カンパニー 人事部長',
    img: b.img,
    faces: b.faces || [[0, '🤬'], [20, '😠'], [40, '😒'], [60, '🤔'], [80, '😏'], [100, '😌']],
    forbiddenEarly: b.forbiddenEarly,
    selfThirdPerson: new RegExp(`(^|[。、！？\\s])${esc(b.title)}(は|が|も)`),
    weaknesses: b.weaknesses, decoys: b.decoys,
    angerRules: [...b.anger, insultRule],
    jargon: b.jargon || null,
    systemPrompt: makePrompt(b),
  };
}

